#!/usr/bin/env python3
"""Turn works-on-duo.txt into GNOME Software's deployment-featured list.

    gen-featured.py works-on-duo.txt > works-on-duo.xml

Every app in the list gets an AppStream merge component carrying
GnomeSoftware::DeploymentFeatured = duo2-os (the Selector in
deployment-featured.ini), so GNOME Software shows them in one section on its
Explore page. Debian's catalogue names some apps with a ".desktop" suffix
(org.gnome.Calculator.desktop) and Flathub without it, so both forms are
written; a merge component for an id nobody has is ignored.
"""

import sys
from xml.sax.saxutils import escape

SELECTOR = "duo2-os"


def read_list(path):
    apps = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].rstrip()
            if not line.strip():
                continue
            fields = line.split("\t")
            app_id = fields[0].strip()
            status = fields[1].strip() if len(fields) > 1 else ""
            if status not in ("tried", "declared"):
                raise SystemExit(f"{path}: {app_id}: status must be tried or declared")
            apps.append(app_id)
    return apps


def ids_for(app_id):
    base = app_id[: -len(".desktop")] if app_id.endswith(".desktop") else app_id
    return [base, base + ".desktop"]


def main():
    apps = read_list(sys.argv[1])
    out = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        "<!-- Generated by shell/duo-apps/software/gen-featured.py from works-on-duo.txt;",
        "     do not edit. -->",
        "<components>",
    ]
    for app_id in apps:
        for i in ids_for(app_id):
            out += [
                '  <component merge="append">',
                f"    <id>{escape(i)}</id>",
                "    <custom>",
                f'      <value key="GnomeSoftware::DeploymentFeatured">{SELECTOR}</value>',
                "    </custom>",
                "  </component>",
            ]
    out.append("</components>")
    print("\n".join(out))


if __name__ == "__main__":
    main()
