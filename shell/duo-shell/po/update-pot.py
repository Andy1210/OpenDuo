#!/usr/bin/python3
"""Write po/duo-shell.pot from the _("...") calls in duoshell/*.py.

No gettext tools needed (the build host has none): Python's ast finds the
calls, a "# Translators:" comment on the line above is kept for translators.

    po/update-pot.py
"""

import ast
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, "..", "duoshell")


def escape(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def main():
    found = {}
    for name in sorted(os.listdir(src)):
        if not name.endswith(".py"):
            continue
        path = os.path.join(src, name)
        with open(path) as f:
            text = f.read()
        lines = text.splitlines()
        for node in ast.walk(ast.parse(text)):
            if (
                isinstance(node, ast.Call)
                and isinstance(node.func, ast.Name)
                and node.func.id == "_"
                and node.args
                and isinstance(node.args[0], ast.Constant)
                and isinstance(node.args[0].value, str)
            ):
                msg = node.args[0].value
                note = None
                prev = lines[node.lineno - 2].strip() if node.lineno >= 2 else ""
                if prev.startswith("# Translators:"):
                    note = prev[2:]
                entry = found.setdefault(msg, {"refs": [], "notes": []})
                entry["refs"].append("duoshell/%s:%d" % (name, node.lineno))
                if note and note not in entry["notes"]:
                    entry["notes"].append(note)
    out = [
        "# duo-shell: the duo2-os status bars and app grid.",
        "# This file is generated by po/update-pot.py; do not edit.",
        'msgid ""',
        'msgstr ""',
        '"Project-Id-Version: duo-shell\\n"',
        '"Content-Type: text/plain; charset=UTF-8\\n"',
        '"Content-Transfer-Encoding: 8bit\\n"',
        "",
    ]

    def where(msg):
        path, line = found[msg]["refs"][0].rsplit(":", 1)
        return path, int(line)

    for msg in sorted(found, key=where):
        entry = found[msg]
        for note in entry["notes"]:
            out.append("#. " + note)
        out.append("#: " + " ".join(entry["refs"]))
        if "%" in msg:
            out.append("#, python-format")
        out.append('msgid "%s"' % escape(msg))
        out.append('msgstr ""')
        out.append("")
    with open(os.path.join(here, "duo-shell.pot"), "w") as f:
        f.write("\n".join(out))
    print("%d strings" % len(found))
    return 0


if __name__ == "__main__":
    sys.exit(main())
